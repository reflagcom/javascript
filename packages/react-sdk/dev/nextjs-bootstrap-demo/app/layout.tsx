import type { Metadata } from "next";
import { Inter } from "next/font/google";

import "./globals.css";
import { EnvironmentWarnings } from "@/components/EnvironmentWarnings";
import { ReflagBootstrappedProvider } from "@reflag/react-sdk";

import { getServerClient, publishableKey, secretKeyConfigured } from "./client";

const inter = Inter({ subsets: ["latin"] });

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  // Get the singleton server client
  const serverClient = await getServerClient();

  // In a real app, you'd get user/company from your auth system
  const flags = serverClient.getFlagsForBootstrap({
    user: {
      id: "demo-user",
      email: "demo-user@example.com",
      "optin-huddles": true,
    },
    company: { id: "demo-company", name: "Demo Company" },
    other: { source: "web" },
  });

  return (
    <html lang="en">
      <body className={inter.className}>
        <EnvironmentWarnings
          publishableKeyConfigured={Boolean(publishableKey)}
          secretKeyConfigured={secretKeyConfigured}
        />
        <ReflagBootstrappedProvider
          publishableKey={publishableKey}
          flags={flags}
          feedback={{ enableAutoFeedback: false }}
          offline={!publishableKey}
          suspense
        >
          {children}
        </ReflagBootstrappedProvider>
      </body>
    </html>
  );
}
